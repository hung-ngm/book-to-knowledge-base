"""Library commands: init, concepts, index, validate, remove-book.

Index Pages are derived from the notes and never edited by hand.
Every write goes through ``write_if_changed`` so each command converges to the
same files however often it runs.
"""

from __future__ import annotations

import json
import os
import re
import shutil
from dataclasses import dataclass
from pathlib import Path

from .model import (
    BOOK_TYPES,
    BOOKS_DIR,
    CHAPTER_STEM_RE,
    CONCEPT_KINDS,
    CONCEPTS_DIR,
    CONFIG_NAME,
    CONTRIBUTION_RE,
    DEPTHS,
    SLUG_RE,
    Library,
    load,
    sections,
    wikilinks,
)

GENERATED = "<!-- Generated by book-to-knowledge-base. Do not edit: run the index command. -->"
CHAPTERS_OPEN = "<!-- kb:chapters -->"
CHAPTERS_CLOSE = "<!-- /kb:chapters -->"
INDEX_PAGES = ("index.md", "glossary.md", "AGENTS.md")


def write_if_changed(path: Path, text: str) -> bool:
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)
    return True


# --- init ---


def init(root: Path, name: str, language: str) -> Path:
    root = root.expanduser().resolve()
    config = root / CONFIG_NAME
    if not config.is_file():
        write_if_changed(config, json.dumps({"schema_version": 1, "name": name, "language": language}, indent=2) + "\n")
    (root / BOOKS_DIR).mkdir(parents=True, exist_ok=True)
    (root / CONCEPTS_DIR).mkdir(parents=True, exist_ok=True)
    gitignore = root / ".gitignore"
    if not gitignore.is_file():
        write_if_changed(gitignore, ".sources/\n")
    index(load(root))
    return root


# --- concepts ---


def concept_list(lib: Library) -> str:
    """Compact listing the agent matches a new Book's ideas against."""
    rows = ["slug\tkind\ttitle\taliases\tbooks"]
    for slug, c in sorted(lib.concepts.items()):
        rows.append(
            "\t".join(
                [
                    slug,
                    str(c.meta.get("concept_kind", "")),
                    str(c.meta.get("title", "")),
                    "; ".join(c.aliases),
                    "; ".join(c.contributions),
                ]
            )
        )
    return "\n".join(rows) + "\n"


# --- index ---


def _definition(body: str) -> str:
    parts = sections(body)
    lead = parts[0][1] if parts and parts[0][0] == "" else ""
    text = " ".join(line for line in lead.splitlines() if line.strip() and not line.startswith("# "))
    match = re.match(r"(.+?[.!?])(\s|$)", text)
    return (match.group(1) if match else text).strip()


def _title(note) -> str:
    return str(note.meta.get("title", note.stem))


def _count(n: int, noun: str) -> str:
    return f"{n} {noun}{'' if n == 1 else 's'}"


def render_index(lib: Library) -> str:
    out = [GENERATED, "", f"# {lib.config.name}", ""]
    out.append(
        f"Library Language: `{lib.config.language}` · {_count(len(lib.books), 'Book')} · "
        f"{_count(len(lib.chapters), 'Chapter Note')} · {_count(len(lib.concepts), 'Concept')}"
    )
    out += ["", "## Books", ""]
    if lib.books:
        out += ["| Book | Authors | Chapters |", "|---|---|---|"]
        for slug, book in sorted(lib.books.items(), key=lambda kv: _title(kv[1]).casefold()):
            authors = ", ".join(book.meta.get("authors") or [])
            out.append(f"| [[{slug}\\|{_title(book)}]] | {authors} | {len(lib.chapters_of(slug))} |")
    else:
        out.append("_No Books yet._")
    out += ["", "## Concepts", ""]
    for kind in CONCEPT_KINDS:
        members = sorted(
            (c for c in lib.concepts.values() if c.meta.get("concept_kind") == kind),
            key=lambda c: _title(c).casefold(),
        )
        if not members:
            continue
        out += [f"### {kind} ({len(members)})", ""]
        for c in members:
            aliases = c.aliases
            aka = f" · aka {'; '.join(aliases)}" if aliases else ""
            books = len(c.contributions)
            out.append(f"- [[{c.stem}|{_title(c)}]]{aka} · {books} book{'s' if books != 1 else ''}")
        out.append("")
    if not lib.concepts:
        out += ["_No Concepts yet._", ""]
    return "\n".join(out).rstrip() + "\n"


def render_glossary(lib: Library) -> str:
    entries: list[tuple[str, str]] = []
    for c in lib.concepts.values():
        definition = _definition(c.body)
        entries.append((_title(c), f"- **{_title(c)}** ({c.meta.get('concept_kind', '')}) → [[{c.stem}]]: {definition}"))
        for alias in c.aliases:
            entries.append((alias, f"- **{alias}** → see [[{c.stem}|{_title(c)}]]"))
    out = [GENERATED, "", "# Glossary", ""]
    out += [line for _, line in sorted(entries, key=lambda e: e[0].casefold())] or ["_No Concepts yet._"]
    return "\n".join(out) + "\n"


def render_agents(lib: Library) -> str:
    return f"""{GENERATED}

# How to read this Library

This folder is a knowledge base of {len(lib.books)} Books, written in `{lib.config.language}`.

- `index.md` lists every Book and every Concept, grouped by kind.
- `glossary.md` maps every Concept name and Alias to its note.
- `concepts/<slug>.md` holds one note per named idea. Each `## In [[<book>]]` section is that Book's Contribution: the author's wording, how to apply it, and links to the chapters. `## Tensions` records where Books disagree.
- `books/<book>/<book>.md` is a Book Note. `books/<book>/<book>-chNN.md` are its Chapter Notes, in the author's order.
- Wikilinks are `[[stem]]`, where `stem` is a filename without `.md`. Every stem is unique, so `find . -name '<stem>.md'` resolves any link.

To answer a question: grep `glossary.md` for the term, open the Concept note, then follow its chapter links for depth.
"""


def render_chapter_block(lib: Library, book: str) -> str:
    lines = [CHAPTERS_OPEN]
    for ch in lib.chapters_of(book):
        lines.append(f"{ch.number}. [[{ch.stem}|{_title(ch)}]]")
    lines.append(CHAPTERS_CLOSE)
    return "\n".join(lines)


def _with_chapter_block(text: str, block: str) -> str:
    start, end = text.find(CHAPTERS_OPEN), text.find(CHAPTERS_CLOSE)
    if start != -1 and end != -1:
        return text[:start] + block + text[end + len(CHAPTERS_CLOSE) :]
    return text.rstrip("\n") + "\n\n## Chapters\n\n" + block + "\n"


def _yaml_item(value: str) -> str:
    if re.fullmatch(r"[A-Za-z0-9][^:#\"']*", value) and not value.endswith(" "):
        return value
    return json.dumps(value, ensure_ascii=False)


def _with_aliases(text: str, aliases: list[str]) -> str:
    """Replace the frontmatter `aliases` entry, in place, with the derived list."""
    end = text.find("\n---\n", 4)
    lines = text[4:end].split("\n")
    rendered = ["aliases:", *(f"  - {_yaml_item(a)}" for a in aliases)] if aliases else ["aliases: []"]
    at = next((i for i, line in enumerate(lines) if line.startswith("aliases:")), None)
    if at is None:
        lines += rendered
    else:
        stop = at + 1
        while stop < len(lines) and lines[stop].lstrip().startswith("- "):
            stop += 1
        lines[at:stop] = rendered
    return "---\n" + "\n".join(lines) + text[end:]


def expected_files(lib: Library) -> dict[Path, str]:
    """Every derived file and the text it must contain."""
    files = {
        lib.root / "index.md": render_index(lib),
        lib.root / "glossary.md": render_glossary(lib),
        lib.root / "AGENTS.md": render_agents(lib),
    }
    for slug, book in lib.books.items():
        current = book.path.read_text(encoding="utf-8")
        files[book.path] = _with_chapter_block(current, render_chapter_block(lib, slug))
    for concept in lib.concepts.values():
        files[concept.path] = _with_aliases(concept.path.read_text(encoding="utf-8"), concept.aliases)
    return files


def index(lib: Library) -> list[Path]:
    return [path for path, text in expected_files(lib).items() if write_if_changed(path, text)]


# --- validate ---


@dataclass(frozen=True)
class Finding:
    severity: str  # "error" | "warning"
    path: str
    message: str

    def __str__(self) -> str:
        return f"{self.severity.upper()}: {self.path}: {self.message}"


def validate(lib: Library) -> list[Finding]:
    found: list[Finding] = []

    def rel(path: Path) -> str:
        return str(path.relative_to(lib.root))

    def err(path: Path, msg: str) -> None:
        found.append(Finding("error", rel(path), msg))

    def warn(path: Path, msg: str) -> None:
        found.append(Finding("warning", rel(path), msg))

    stems: dict[str, Path] = {}
    for note in lib.all_notes():
        if note.stem in stems:
            err(note.path, f"filename stem {note.stem!r} also used by {rel(stems[note.stem])}")
        stems[note.stem] = note.path
        if not note.meta.get("title"):
            err(note.path, "missing 'title'")

    for slug, book in lib.books.items():
        if not SLUG_RE.match(slug):
            err(book.path, f"book slug {slug!r} must be lowercase words joined by '-'")
        if book.path.parent.name != slug:
            err(book.path, f"Book Note must live in books/{slug}/")
        if not book.meta.get("authors"):
            err(book.path, "missing 'authors'")
        if book.meta.get("book_type") not in BOOK_TYPES:
            err(book.path, f"book_type must be one of {', '.join(BOOK_TYPES)}")
        if book.meta.get("depth") not in DEPTHS:
            err(book.path, f"depth must be one of {', '.join(DEPTHS)}")

    for stem, ch in lib.chapters.items():
        match = CHAPTER_STEM_RE.match(stem)
        if not match or match.group("book") != ch.book:
            err(ch.path, f"Chapter Note filename must be '{ch.book}-chNN.md'")
        if ch.book not in lib.books:
            err(ch.path, f"book {ch.book!r} has no Book Note")
        elif ch.path.parent.name != ch.book:
            err(ch.path, f"Chapter Note must live in books/{ch.book}/")

    names: dict[str, str] = {}
    for slug, c in lib.concepts.items():
        if not SLUG_RE.match(slug):
            err(c.path, f"concept slug {slug!r} must be lowercase words joined by '-'")
        if c.meta.get("concept_kind") not in CONCEPT_KINDS:
            err(c.path, f"concept_kind must be one of {', '.join(CONCEPT_KINDS)}")
        for name in [str(c.meta.get("title", "")), *c.aliases]:
            key = name.casefold().strip()
            if not key:
                continue
            if key in names and names[key] != slug:
                err(c.path, f"name {name!r} is also a title or alias of concepts/{names[key]}.md")
            names.setdefault(key, slug)
        if not c.contributions:
            err(c.path, "no Contribution: add a '## In [[<book>]]' section")
        for book in c.contributions:
            if book not in lib.books:
                err(c.path, f"Contribution names {book!r}, which is not a Book")
        if len(set(c.contributions)) != len(c.contributions):
            err(c.path, "a Book has more than one Contribution")
        has_tensions = any(h == "## Tensions" for h, _ in sections(c.body))
        if has_tensions and len(set(c.contributions)) < 2:
            warn(c.path, "'## Tensions' needs at least two Contributions")

    linked_from_chapters = {link for ch in lib.chapters.values() for link in ch.links}
    for slug, c in lib.concepts.items():
        if slug not in linked_from_chapters:
            warn(c.path, "orphan: no Chapter Note links to this Concept")

    for note in lib.all_notes():
        for target in note.links:
            if target not in stems:
                err(note.path, f"broken wikilink [[{target}]]")

    for path, text in expected_files(lib).items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != text:
            err(path, "out of date: run the index command (never edit it by hand)")
    return found


# --- reader skill ---


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.casefold()).strip("-") or "library"


def reader_skill_name(lib: Library) -> str:
    return f"{_slug(lib.config.name)}-library"[:64].strip("-")


def render_reader_skill(lib: Library) -> str:
    name = reader_skill_name(lib)
    titles = [_title(b) for _, b in sorted(lib.books.items(), key=lambda kv: _title(kv[1]).casefold())]
    shared = sorted(lib.concepts.values(), key=lambda c: (-len(c.contributions), _title(c).casefold()))
    topics = [_title(c) for c in shared[:12]]
    description = (
        f"Knowledge base of {len(titles)} book(s): {'; '.join(titles) or 'none yet'}. "
        f"Use to answer questions with these books' ideas, compare authors, or look up concepts"
        + (f" such as {', '.join(topics)}." if topics else ".")
    )
    if len(description) > 1024:
        description = description[:1020].rsplit(" ", 1)[0] + " ..."
    description = description.replace('"', "'")
    return f"""---
name: {name}
description: "{description}"
---

# {lib.config.name}

The Library lives at `{lib.root}`. It is plain markdown, written in `{lib.config.language}`.

1. Read `{lib.root}/AGENTS.md` once: it explains the layout.
2. To answer a question, grep `{lib.root}/glossary.md` for the term, open the Concept note it points to, then follow its chapter links.
3. To compare authors, read each `## In [[<book>]]` section of a Concept and its `## Tensions`.
4. Cite the Book and chapter for every claim. Say so when the Library does not cover something.

This skill only reads. To add or remove a Book, use the `book-to-knowledge-base` skill.
"""


def write_reader_skill(lib: Library, skills_root: Path) -> Path:
    path = skills_root.expanduser().resolve() / reader_skill_name(lib) / "SKILL.md"
    write_if_changed(path, render_reader_skill(lib))
    return path


# --- relink ---


def read_link_map(path: Path) -> dict[str, str]:
    """Parse 'old<TAB>new' lines; blank lines and '#' comments are skipped."""
    mapping = {}
    for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) != 2 or not all(SLUG_RE.match(x.strip()) for x in parts):
            raise ValueError(f"{path}:{lineno}: expected 'old-slug<TAB>new-slug'")
        mapping[parts[0].strip()] = parts[1].strip()
    return mapping


def relink(directory: Path, mapping: dict[str, str]) -> list[Path]:
    """Rewrite [[old...]] link targets to [[new...]] in every note under *directory*."""
    pattern = re.compile(r"\[\[([^\]|#]+)(?=[\]|#])")

    def swap(match: re.Match) -> str:
        target = match.group(1).strip()
        return "[[" + mapping.get(target, match.group(1))

    changed = []
    for path in sorted(directory.rglob("*.md")):
        text = path.read_text(encoding="utf-8")
        if write_if_changed(path, pattern.sub(swap, text)):
            changed.append(path)
    return changed


# --- remove-book ---


@dataclass
class RemoveReport:
    deleted_concepts: list[str]
    edited_concepts: list[str]
    stale_prose: list[str]


def _drop_sections(body: str, drop) -> str:
    kept = []
    for heading, text in sections(body):
        if heading and drop(heading):
            continue
        kept.append(f"{heading}\n{text}" if heading else text)
    return "".join(kept)


def _prune_related(body: str, gone: set[str]) -> str:
    """Drop `## Related` bullets that point at removed notes, and the heading if none remain."""
    kept = []
    for heading, text in sections(body):
        if heading == "## Related":
            lines = [
                line for line in text.splitlines(keepends=True)
                if not (line.startswith("- ") and wikilinks(line)[:1] and wikilinks(line)[0] in gone)
            ]
            if not any(line.startswith("- ") for line in lines):
                continue
            text = "".join(lines)
        kept.append(f"{heading}\n{text}" if heading else text)
    return "".join(kept)


def remove_book(lib: Library, book: str) -> RemoveReport:
    if book not in lib.books:
        raise KeyError(f"no Book {book!r} in this Library")
    deleted = sorted(slug for slug, c in lib.concepts.items() if set(c.contributions) == {book})
    gone = {book, *(ch.stem for ch in lib.chapters_of(book)), *deleted}
    report = RemoveReport(deleted, [], [])
    for slug in deleted:
        lib.concepts[slug].path.unlink()
    for slug, c in sorted(lib.concepts.items()):
        if slug in gone:
            continue
        body = c.body
        if book in c.contributions:
            single = len({b for b in c.contributions if b != book}) < 2

            def drop(heading: str) -> bool:
                match = CONTRIBUTION_RE.match(heading)
                if match and match.group(1).strip() == book:
                    return True
                return single and heading == "## Tensions"

            body = _drop_sections(body, drop)
        body = _prune_related(body, gone)
        if body != c.body:
            body = body.rstrip("\n") + "\n"
            text = c.path.read_text(encoding="utf-8")
            write_if_changed(c.path, text[: len(text) - len(c.body)] + body)
            report.edited_concepts.append(slug)
        if gone & set(wikilinks(body)):
            report.stale_prose.append(slug)
    shutil.rmtree(lib.root / BOOKS_DIR / book)
    index(load(lib.root))
    return report
